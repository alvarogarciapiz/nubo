import Foundation

public enum HIDKeyMap {
    // USB HID Usage Tables keyboard page -> macOS virtual key codes.
    public static func macVirtualKeyCode(for usage: UInt16) -> UInt16? {
        keyCodes[usage]
    }

    private static let keyCodes: [UInt16: UInt16] = [
        0x04: 0x00, 0x05: 0x0B, 0x06: 0x08, 0x07: 0x02, // A-D
        0x08: 0x0E, 0x09: 0x03, 0x0A: 0x05, 0x0B: 0x04, // E-H
        0x0C: 0x22, 0x0D: 0x26, 0x0E: 0x28, 0x0F: 0x25, // I-L
        0x10: 0x2E, 0x11: 0x2D, 0x12: 0x1F, 0x13: 0x23, // M-P
        0x14: 0x0C, 0x15: 0x0F, 0x16: 0x01, 0x17: 0x11, // Q-T
        0x18: 0x20, 0x19: 0x09, 0x1A: 0x0D, 0x1B: 0x07, // U-X
        0x1C: 0x10, 0x1D: 0x06,                         // Y-Z
        0x1E: 0x12, 0x1F: 0x13, 0x20: 0x14, 0x21: 0x15, // 1-4
        0x22: 0x17, 0x23: 0x16, 0x24: 0x1A, 0x25: 0x1C, // 5-8
        0x26: 0x19, 0x27: 0x1D,                         // 9-0
        0x28: 0x24, // Return
        0x29: 0x35, // Escape
        0x2A: 0x33, // Delete/backspace
        0x2B: 0x30, // Tab
        0x2C: 0x31, // Space
        0x4C: 0x75, // Forward delete
        0x4F: 0x7C, 0x50: 0x7B, 0x51: 0x7D, 0x52: 0x7E, // Arrows
        0x3A: 0x7A, 0x3B: 0x78, 0x3C: 0x63, 0x3D: 0x76, // F1-F4
        0x3E: 0x60, 0x3F: 0x61, 0x40: 0x62, 0x41: 0x64, // F5-F8
        0x42: 0x65, 0x43: 0x6D, 0x44: 0x67, 0x45: 0x6F  // F9-F12
    ]
}
